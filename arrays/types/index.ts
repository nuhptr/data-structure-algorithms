const stringArray: string[] = ["apple", "banana", "cherry"]
console.log(stringArray) // Output: ["apple", "banana", "cherry"]

const numberArray: number[] = [1, 2, 3, 4, 5]
console.log(numberArray) // Output: [1, 2, 3, 4, 5]

const booleanArray: boolean[] = [true, false, true]
console.log(booleanArray) // Output: [true, false, true]

const mixedArray: (string | number | boolean)[] = ["hello", 42, true, "world", 3.14]
console.log(mixedArray) // Output: ["hello", 42, true, "world", 3.14]

const nullableArray: (string | null)[] = ["apple", null, "banana", null, "cherry"]
console.log(nullableArray) // Output: ["apple", null, "banana", null, "cherry"]
